# ── Task builders ─────────────────────────────────────────────────────


def build_all_tasks() -> dict[str, list[TaskDef]]:
    tasks: dict[str, list[TaskDef]] = {}
    for domain in DOMAIN_TOOLS:
        specs = _TASK_SPECS.get(domain, {})
        domain_tasks = []
        for task_id_suffix, spec in sorted(specs.items()):
            domain_tasks.append(_build_task(spec, domain))
        tasks[domain] = domain_tasks
    return tasks


def get_oracle_actions(task: TaskDef) -> list[AgentAction]:
    task_suffix = task.task_id.split("-", 1)[1]
    domain = task.domain
    spec = _TASK_SPECS.get(domain, {}).get(task_suffix)
    if spec is None:
        return []
    return _build_actions(spec["oracle"])


# ── Fault variants ───────────────────────────────────────────────────


def _hazard_type(task_id: str, fault_idx: int) -> str:
    return [
        "execution_error",
        "schema_drift",
        "partial_output",
        "silent_corruption",
        "cross_source_conflict",
    ][fault_idx % 5]


def generate_fault_schedules(
    task: TaskDef,
    fault_idx: int,
) -> list[FaultSchedule]:
    if task.category != "tool_required":
        return []

    oracle = get_oracle_actions(task)
    tool_steps = [
        (i, a) for i, a in enumerate(oracle) if isinstance(a, ToolCall)
    ]
    if not tool_steps:
        return []

    hazard = _hazard_type(task.task_id, fault_idx)
    step_index, tool_call = tool_steps[fault_idx % len(tool_steps)]

    return [
        FaultSchedule(
            task_id=task.task_id,
            fault_type=hazard,
            step_index=step_index,
            tool_name=tool_call.name if isinstance(tool_call, ToolCall) else "",
            config={},
        )
    ]


# ── Split logic ───────────────────────────────────────────────────────


SplitName = str  # "train" | "dev" | "test"


def get_split(task: TaskDef) -> SplitName:
    if task.domain in _TRAINING_DOMAINS:
        suffix = task.task_id.split("-", 1)[1]
        num = int(suffix)
        if num <= 24:
            return "train"
        elif num <= 30:
            return "dev"
        else:
            return "test"
    return "test"


def domain_hazard_quadrant(task: TaskDef, hazard: str) -> str:
    domain_seen = "seen" if task.domain in _TRAINING_DOMAINS else "unseen"
    hazard_seen = "seen" if hazard in _TRAINING_HAZARDS else "unseen"
    return f"{domain_seen}-domain/{hazard_seen}-hazard"


# ── Task manifest ─────────────────────────────────────────────────────


def build_manifest() -> dict[str, Any]:
    all_tasks = build_all_tasks()
    manifest = {
        "version": "0.2.0",
        "total_tasks": sum(len(t) for t in all_tasks.values()),
        "domains": DOMAIN_TOOLS,
        "training_domains": sorted(_TRAINING_DOMAINS),
        "heldout_domains": sorted(_HELDOUT_DOMAINS),
        "training_hazards": sorted(_TRAINING_HAZARDS),
        "heldout_hazards": sorted(_HELDOUT_HAZARDS),
        "splits": {},
        "tasks": {},
    }
    for domain, tasks in all_tasks.items():
        for task in tasks:
            split = get_split(task)
            manifest["splits"].setdefault(split, 0)
            manifest["splits"][split] += 1
            manifest["tasks"][task.task_id] = {
                "domain": task.domain,
                "category": task.category,
                "split": split,
                "available_tools": task.available_tools,
                "num_claims": len(task.canonical_claims),
            }
    return manifest


def get_faulted_tasks(tasks: list[TaskDef]) -> list[tuple[TaskDef, int]]:
    result = []
    for task in tasks:
        if task.category == "tool_required":
            for fault_idx in range(5):
                result.append((task, fault_idx))
    return result

