def _call(name: str, **args: Any) -> ToolCall:
    return ToolCall(name=name, arguments=args)


def _answer(text: str) -> FinalAnswer:
    return FinalAnswer(text=text)


def _clarify(text: str) -> Clarify:
    return Clarify(text=text)


def _abort(reason: str) -> Abort:
    return Abort(reason=reason)


# ── Task specification format ────────────────────────────────────────
#
# Each task is a dict with:
#   id: str
#   query: str
#   category: "tool_required" | "no_tool" | "missing_information"
#   tools: list[str]
#   oracle: list of action tuples: (action_type, **kwargs)
#   claims: list[str] (what a correct final answer should mention)
#   alt_oracles: list[list[...]] (alternative valid trajectories)


def _build_task(spec: dict[str, Any], domain: str) -> TaskDef:
    category = spec["category"]
    oracle_actions = _build_actions(spec["oracle"])

    alt_trajectories = []
    for alt in spec.get("alt_oracles", []):
        alt_trajectories.append([t.name if isinstance(t, ToolCall) else "" for t in _build_actions(alt)])

    return TaskDef(
        task_id=f"{domain[:4].upper()}-{spec['id']}",
        domain=domain,
        user_query=spec["query"],
        category=category,
        available_tools=spec.get("tools", []),
        canonical_claims=spec.get("claims", []),
        valid_tool_sequences=[[t.name for t in oracle_actions if isinstance(t, ToolCall)]],
        fault_variants=spec.get("fault_variants", []),
    )


def _build_actions(raw: list[Any]) -> list[AgentAction]:
    actions: list[AgentAction] = []
    for item in raw:
        if isinstance(item, str):
            if item == "FINAL":
                actions.append(_answer(""))
            else:
                actions.append(_clarify(item))
        elif isinstance(item, dict):
            kind = item.get("type", "")
            if kind == "call":
                name = item["name"]
                args = {k: v for k, v in item.items() if k not in ("type", "name")}
                actions.append(_call(name, **args))
            elif kind == "answer":
                actions.append(_answer(item.get("text", "")))
            elif kind == "clarify":
                actions.append(_clarify(item.get("text", "")))
            elif kind == "abort":
                actions.append(_abort(item.get("reason", "")))
        elif isinstance(item, (list, tuple)):
            actions.extend(_build_actions(list(item)))
    return actions


def _get_oracle(task: TaskDef) -> list[AgentAction]:
    return _build_actions(_TASK_SPECS[task.domain][task.task_id.split("-", 1)[1]]["oracle"])


# ── Task specs by domain ─────────────────────────────────────────────

_TASK_SPECS: dict[str, dict[str, dict[str, Any]]] = {}


def _register(domain: str, specs: list[dict[str, Any]]) -> None:
    _TASK_SPECS[domain] = {}
    for spec in specs:
        _TASK_SPECS[domain][spec["id"]] = spec


